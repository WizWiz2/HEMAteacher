// Builds src/follow/referenceClips.json: one looping reference skeleton per drill and camera view for the
// follow-along mode, cut from clean master renders in the pose fixture (test-fixtures/motion-poses.json.gz).
// Usage: node scripts/build-follow-references.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadMotionFixture } from "../test-fixtures/loadFixture.mjs";

const OUT = fileURLToPath(new URL("../src/follow/referenceClips.json", import.meta.url));
export const JOINTS = ["nose", "left_shoulder", "right_shoulder", "left_elbow", "right_elbow", "left_wrist", "right_wrist",
  "left_hip", "right_hip", "left_knee", "right_knee", "left_ankle", "right_ankle", "left_foot_index", "right_foot_index"];
const DRILLS = ["zornhau", "scheitelhau", "krumphau", "zwerchhau", "schielhau", "advance", "retreat", "passing-step-forward", "passing-step-backward"];
const FPS = 15, PAD_MS = 450;
const LEVEL = { master: 0, experienced: 1, beginner: 2 };

const fixture = loadMotionFixture();
const index = Object.fromEntries(fixture.names.map((n, i) => [n, i]));
const view = c => (c.variant.startsWith("front:") || c.variant === "real:front" ? "front" : "side");

function pick(drill, v) {
  const pool = fixture.clips.filter(c => c.drill === drill && c.move && view(c) === v && !c.variant.startsWith("real")
    && (v === "front" ? c.variant === "front:train" : c.variant === "main"));
  pool.sort((a, b) => (LEVEL[a.level] ?? 3) - (LEVEL[b.level] ?? 3) || (a.body === "avg_longlimb_female" ? -1 : 0) - (b.body === "avg_longlimb_female" ? -1 : 0) || a.id.localeCompare(b.id));
  return pool[0];
}

function point(clip, i, name) {
  const p = clip.p[i], k = index[name];
  if (!p?.length) return null;
  return [p[3 * k] / 1e4 * clip.width, p[3 * k + 1] / 1e4 * clip.height, p[3 * k + 2] / 100];
}

function build(clip) {
  // Active span: frames where wrists/ankles move away from where they were a few frames earlier; the clip
  // contains guard -> movement -> hold -> return -> guard, all of which loop naturally.
  const moving = [];
  for (let i = 3; i < clip.t.length; i++) {
    let m = 0;
    for (const n of ["left_wrist", "right_wrist", "left_ankle", "right_ankle"]) {
      const a = point(clip, i, n), b = point(clip, i - 3, n);
      if (a && b) m = Math.max(m, Math.hypot(a[0] - b[0], a[1] - b[1]) / clip.height);
    }
    if (m > 0.006) moving.push(clip.t[i]);
  }
  const first = clip.t[clip.p.findIndex(p => p.length)];
  const start = Math.max(first, (moving[0] ?? clip.move[0]) - PAD_MS);
  const end = Math.min(clip.t.at(-1), (moving.at(-1) ?? clip.move[1]) + PAD_MS);
  // Normalise: origin at the hip centre of the first frame, unit = its shoulder-to-hip (torso) length.
  const i0 = clip.t.findIndex((t, i) => t >= start && clip.p[i].length);
  const mid = (a, b) => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
  const hip = mid(point(clip, i0, "left_hip"), point(clip, i0, "right_hip"));
  const sh = mid(point(clip, i0, "left_shoulder"), point(clip, i0, "right_shoulder"));
  const torso = Math.hypot(sh[0] - hip[0], sh[1] - hip[1]);
  const frames = [];
  for (let t = start; t <= end; t += 1000 / FPS) {
    let i = clip.t.findIndex((x, k) => x >= t && clip.p[k].length);
    if (i < 0) break;
    const row = [];
    for (const n of JOINTS) {
      const p = point(clip, i, n);
      row.push(p && p[2] >= 0.3 ? Math.round((p[0] - hip[0]) / torso * 1000) : null, p && p[2] >= 0.3 ? Math.round((p[1] - hip[1]) / torso * 1000) : null);
    }
    frames.push(row);
  }
  return { source: clip.id, fps: FPS, moveMs: [Math.round(clip.move[0] - start), Math.round(clip.move[1] - start)], frames };
}

const out = { joints: JOINTS, note: "Generated by scripts/build-follow-references.mjs from test-fixtures/motion-poses.json.gz. Coordinates: torso lengths x1000 from the first frame's hip centre, image axes (y down).", clips: {} };
for (const v of ["front", "side"]) for (const d of DRILLS) {
  const clip = pick(d, v);
  if (!clip) { console.warn(`no ${v} reference for ${d}`); continue; }
  out.clips[`${v}:${d}`] = build(clip);
}
const json = JSON.stringify(out);
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== json) { console.error("referenceClips.json is stale: run node scripts/build-follow-references.mjs"); process.exit(1); }
  console.log("follow-along references are up to date");
} else {
  writeFileSync(OUT, json);
  console.log(`wrote ${OUT} (${(json.length / 1024).toFixed(0)} KB, ${Object.keys(out.clips).length} clips)`);
  for (const [k, c] of Object.entries(out.clips)) console.log(k, c.source, c.frames.length, "frames");
}
